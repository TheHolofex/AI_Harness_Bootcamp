#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { figureOutputName, renderResourceFigure } from "./resource-figure-kit.mjs";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPT_DIR, "..");
const CATALOG_PATH = path.join(ROOT, "resources", "catalog.json");
const CHECK_ONLY = process.argv.includes("--check");
const GENERATED = "<!-- GENERATED by scripts/build-resources.mjs. DO NOT EDIT. -->";

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function html(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function write(file, content) {
  const normalized = content.endsWith("\n") ? content : `${content}\n`;
  if (CHECK_ONLY) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== normalized) {
      throw new Error(`generated output is stale: ${path.relative(ROOT, file)}`);
    }
    return;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, normalized);
}

function moduleFor(catalog, id) {
  const module = catalog.modules.find((item) => item.id === id);
  if (!module) throw new Error(`unknown module ${id}`);
  return module;
}

function publicResources(catalog) {
  return catalog.resources
    .filter((resource) => resource.status === "published")
    .sort((a, b) => {
      const ma = moduleFor(catalog, a.module).order;
      const mb = moduleFor(catalog, b.module).order;
      return ma - mb || a.id.localeCompare(b.id, undefined, { numeric: true });
    });
}

function canonicalHref(resource, fromSiteDepth) {
  const target = resource.canonical.path.replace(/^site\//, "");
  const fragment = resource.canonical.fragment ? `#${resource.canonical.fragment}` : "";
  return `${fromSiteDepth}/${target}${fragment}`;
}

function extractContents(fragment, resourceId) {
  const sections = [];
  const re = /<section\b[^>]*\bid="([^"]+)"[^>]*>[\s\S]*?<h2\b[^>]*>([\s\S]*?)<\/h2>/gi;
  let match;
  while ((match = re.exec(fragment))) {
    const label = match[2].replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
    sections.push({ id: match[1], label });
  }
  if (sections.length < 5 && resourceId !== "PC-1") {
    throw new Error(`${resourceId}: body needs at least five identified h2 sections`);
  }
  return sections;
}

function renderFigureBlock(figure, moduleId) {
  const filename = figureOutputName(figure);
  return `<figure class="resource-figure" id="figure-${html(figure.id)}">
  <div class="resource-figure-scroll" tabindex="0" aria-label="Scrollable figure">
    <img src="../../assets/resources/${html(moduleId)}/${html(filename)}" width="1120" height="280" alt="${html(figure.desc)}" />
  </div>
  <figcaption><strong>${html(figure.title)}.</strong> ${html(figure.caption)} <span class="figure-expand"><a href="../../assets/resources/${html(moduleId)}/${html(filename)}">Open the full-size figure</a>.</span></figcaption>
  <details class="figure-transcript"><summary>Figure transcript</summary><p>${html(figure.transcript)}</p></details>
</figure>`;
}

function bindFigures(fragment, spec, resource) {
  let output = fragment;
  for (const figure of spec.figures) {
    const marker = new RegExp(`<figure\\s+data-resource-figure=["']${figure.role}["']\\s*><\\/figure>`, "i");
    if (!marker.test(output)) throw new Error(`${resource.id}: body is missing figure role ${figure.role}`);
    output = output.replace(marker, renderFigureBlock(figure, resource.module));
  }
  const unbound = output.match(/data-resource-figure=/g);
  if (unbound) throw new Error(`${resource.id}: body contains an unbound figure marker`);
  return output;
}

function brand(prefix) {
  return `<header class="site-header">
  <div class="site-header-inner">
    <a class="brand" href="${prefix}/index.html">
      <span class="mark-disc" aria-hidden="true"></span>
      <span class="brand-text"><strong>STARZL</strong><span>ENTERPRISES</span></span>
    </a>
    <nav class="nav" id="primary-nav" aria-label="Primary"></nav>
  </div>
</header>`;
}

function pageHead(title, cssPrefix, extraClass = "") {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${html(title)} · AI Harness Bootcamp</title>
  <link rel="stylesheet" href="${cssPrefix}/css/course.css" />
  <link rel="stylesheet" href="${cssPrefix}/css/resources.css" />
</head>
<body${extraClass}>`;
}

function footer(returnRoute) {
  return `<footer class="site-footer">
  <div class="site-footer-inner">
    <div>AI Harness Bootcamp · Operator school · Starzl Enterprises</div>
    <div><a href="${returnRoute.href}">← Return to ${html(returnRoute.label)}</a></div>
  </div>
</footer>`;
}

function scripts(prefix) {
  return `<script src="${prefix}/js/registry.js"></script>
<script src="${prefix}/js/shell.js"></script>`;
}

function relatedCards(resource, resources) {
  const related = resource.related
    .map((id) => resources.find((candidate) => candidate.id === id))
    .filter(Boolean);
  if (!related.length) return "";
  return `<section class="resource-related" aria-labelledby="related-heading">
  <h2 id="related-heading">Optional related handouts</h2>
  <p>Stay on the live module unless another guide answers a problem you have now.</p>
  <div class="card-grid">${related.map((item) => {
    const href = item.module === resource.module
      ? `./${item.slug}.html`
      : `../${item.module}/${item.slug}.html`;
    return `<a class="card" href="${href}"><span class="resource-id">${html(item.id)}</span><h3>${html(item.title)}</h3><p>${html(item.summary)}</p></a>`;
  }).join("\n")}</div>
</section>`;
}

function returnToCourse(href, label) {
  return `<nav class="resource-plate" aria-label="Return to the live course module">
  <a href="${href}"><span>← Return to the live module</span><strong>${html(label)}</strong></a>
</nav>`;
}

let catalog;

function renderHandout(resource, allResources) {
  const sourcePath = path.join(ROOT, "resources", "handouts", resource.module, `${resource.slug}.html`);
  const figurePath = path.join(ROOT, "resources", "figures", resource.module, `${resource.id}.json`);
  if (!fs.existsSync(sourcePath)) throw new Error(`${resource.id}: missing ${path.relative(ROOT, sourcePath)}`);
  if (!fs.existsSync(figurePath)) throw new Error(`${resource.id}: missing ${path.relative(ROOT, figurePath)}`);
  const spec = readJson(figurePath);
  const raw = fs.readFileSync(sourcePath, "utf8").trim()
    .replace(/href=(['"])\/site\//g, "href=$1../../");
  const contents = extractContents(raw, resource.id);
  const body = bindFigures(raw, spec, resource);
  const canonical = canonicalHref(resource, "../..");
  const toc = contents.length ? `<nav class="resource-toc" aria-label="On this page"><p>On this page</p><ol>${contents.map((item) => `<li><a href="#${html(item.id)}">${html(item.label)}</a></li>`).join("")}</ol></nav>` : "";
  const printPath = `/site/resources/${resource.module}/${resource.slug}.html`;

  for (const figure of spec.figures) {
    const svg = renderResourceFigure(figure, resource.id);
    write(path.join(ROOT, "site", "assets", "resources", resource.module, figureOutputName(figure)), svg);
  }

  return `${GENERATED}
${pageHead(resource.title, "../..", ` data-section="resources" data-module="${html(resource.module)}" data-resource="${html(resource.id)}"`)}
<a class="skip-link" href="#main-content">Skip to content</a>
${brand("../..")}
<main class="site-main resource-main" id="main-content">
  <nav class="breadcrumbs" aria-label="Breadcrumb"><ol><li><a href="${canonical}">← Return to ${html(resource.canonical.label)}</a></li><li>Optional handout</li><li aria-current="page">${html(resource.id)}</li></ol></nav>
  <header class="resource-hero">
    <p class="eyebrow">Optional handout · ${html(resource.id)}</p>
    <h1>${html(resource.title)}</h1>
    <p class="lede">${html(resource.summary)}</p>
    <div class="meta-grid resource-meta">
      <div><span class="k">Use when</span><span class="v">${html(resource.useWhen)}</span></div>
      <div><span class="k">Working time</span><span class="v">${html(resource.time)}</span></div>
      <div><span class="k">Leave with</span><span class="v">${html(resource.artifact)}</span></div>
    </div>
    <p class="course-connection"><a class="btn" href="${canonical}">← Return to ${html(resource.canonical.label)}</a></p>
    <p class="course-connection"><strong>This page is optional.</strong> The owning module remains the live course path and source for current tool details.</p>
  </header>
  ${toc}
  <article class="resource-body">
${body}
  </article>
  ${relatedCards(resource, allResources)}
  ${returnToCourse(canonical, resource.canonical.label)}
  <p class="print-source" aria-hidden="true">${html(resource.id)} · ${html(resource.title)} · ${html(printPath)}</p>
</main>
${footer({ href: canonical, label: resource.canonical.label })}
${scripts("../..")}
</body>
</html>`;
}

function resourceCard(resource, href) {
  return `<li><a class="resource-card" href="${href}">
  <span class="resource-card-top"><span class="resource-id">${html(resource.id)}</span><span>${html(resource.time)}</span></span>
  <h3>${html(resource.title)}</h3>
  <p>${html(resource.summary)}</p>
  <dl><div><dt>Use when</dt><dd>${html(resource.useWhen)}</dd></div><div><dt>Artifact</dt><dd>${html(resource.artifact)}</dd></div></dl>
</a></li>`;
}

function renderModulePage(module, moduleResources) {
  const canonicalTarget = `../../${module.canonicalPath.replace(/^site\//, "")}`;
  const existing = (catalog.existingResources || []).filter((item) => item.module === module.id);
  return `${GENERATED}
${pageHead(`${module.label} optional handouts`, "../..", ` data-section="resources" data-module="${html(module.id)}"`)}
<a class="skip-link" href="#main-content">Skip to content</a>
${brand("../..")}
<main class="site-main resource-index" id="main-content">
  <nav class="breadcrumbs" aria-label="Breadcrumb"><ol><li><a href="${canonicalTarget}">← Return to ${html(module.label)}</a></li><li aria-current="page">Optional handouts</li></ol></nav>
  <header class="resource-index-hero"><p class="eyebrow">Optional handouts</p><h1>${html(module.label)} handouts</h1><p class="lede">Use a guide only when the live problem calls for more practice or a reusable instrument. The module page remains the course path.</p><p><a class="btn" href="${canonicalTarget}">← Return to ${html(module.label)}</a></p></header>
  ${moduleResources.length ? `<ol class="resource-card-grid">${moduleResources.map((item) => resourceCard(item, `./${item.slug}.html`)).join("\n")}</ol>` : `<div class="callout"><strong>No field guide is published here yet.</strong> Use the module page for the current course path.</div>`}
${existing.length ? `<section><h2>Optional course-wide companions</h2><div class="card-grid">${existing.map((item) => `<a class="card" href="../../${item.path.replace(/^site\//, "")}"><h3>${html(item.title)}</h3><p>${html(item.summary)}</p></a>`).join("\n")}</div></section>` : ""}
  ${returnToCourse(canonicalTarget, module.label)}
</main>
${footer({ href: canonicalTarget, label: module.label })}
${scripts("../..")}
</body>
</html>`;
}

function renderHub(resources) {
  const liveModules = catalog.modules.filter((module) => resources.some((item) => item.module === module.id) || (catalog.existingResources || []).some((item) => item.module === module.id));
  return `${GENERATED}
${pageHead("Optional handouts", ".", ` data-section="resources"`)}
<a class="skip-link" href="#main-content">Skip to content</a>
${brand(".")}
<main class="site-main resource-hub" id="main-content">
  <header class="resource-index-hero"><p class="eyebrow">Optional reference library</p><h1>Optional handouts</h1><p class="lede">These guides are extra practice and desk references. They are not the course path; return to the day-by-day modules for the class sequence.</p><p><a class="btn" href="./index.html#journey">← Return to the day-by-day course</a></p></header>
  <div class="callout"><strong>Use a handout when a module points you here or a live problem needs more depth.</strong> Each card states the time and the artifact you will leave with.</div>
  <section aria-labelledby="module-shelves"><h2 id="module-shelves">Optional handouts by owning module</h2><div class="module-shelf-grid">${liveModules.map((module) => {
    const count = resources.filter((item) => item.module === module.id).length + (catalog.existingResources || []).filter((item) => item.module === module.id).length;
    return `<a class="module-shelf" href="./resources/${module.route}/index.html"><span class="resource-id">${html(module.code)}</span><h3>${html(module.label.replace(/^P\d · /, ""))}</h3><p>${count} ${count === 1 ? "handout" : "handouts"} · open the optional shelf</p></a>`;
  }).join("\n")}</div></section>
  <section aria-labelledby="field-guides"><h2 id="field-guides">All optional handouts</h2><ol class="resource-card-grid">${resources.map((item) => resourceCard(item, `./resources/${item.module}/${item.slug}.html`)).join("\n")}</ol></section>
</main>
${footer({ href: "./index.html#journey", label: "the day-by-day course" })}
${scripts(".")}
</body>
</html>`;
}

function validateCatalog(value) {
  if (value.schemaVersion !== 1 || !Array.isArray(value.modules) || !Array.isArray(value.resources)) throw new Error("catalog schema is invalid");
  const ids = new Set();
  const slugs = new Set();
  const allowedStatus = new Set(["draft", "published"]);
  const required = ["id", "module", "slug", "title", "summary", "useWhen", "time", "artifact", "canonical", "figurePolicy", "related"];
  for (const resource of value.resources) {
    for (const key of required) if (resource[key] === undefined || resource[key] === "") throw new Error(`${resource.id || "resource"}: missing ${key}`);
    if (ids.has(resource.id)) throw new Error(`duplicate resource id ${resource.id}`);
    ids.add(resource.id);
    const route = `${resource.module}/${resource.slug}`;
    if (slugs.has(route)) throw new Error(`duplicate resource route ${route}`);
    slugs.add(route);
    moduleFor(value, resource.module);
    if (!allowedStatus.has(resource.status)) throw new Error(`${resource.id}: invalid status ${resource.status}`);
    if (!Array.isArray(resource.related)) throw new Error(`${resource.id}: related must be an array`);
    if (!fs.existsSync(path.join(ROOT, resource.canonical.path))) throw new Error(`${resource.id}: canonical path missing on disk`);
  }
  for (const resource of value.resources) {
    for (const related of resource.related) if (!ids.has(related)) throw new Error(`${resource.id}: unknown related resource ${related}`);
  }
}

function main() {
  catalog = readJson(CATALOG_PATH);
  validateCatalog(catalog);
  const resources = publicResources(catalog);
  for (const resource of resources) {
    const output = renderHandout(resource, resources);
    write(path.join(ROOT, "site", "resources", resource.module, `${resource.slug}.html`), output);
  }
  for (const module of catalog.modules) {
    const moduleResources = resources.filter((resource) => resource.module === module.id);
    write(path.join(ROOT, "site", "resources", module.route, "index.html"), renderModulePage(module, moduleResources));
  }
  write(path.join(ROOT, "site", "resources.html"), renderHub(resources));
  process.stdout.write(`${CHECK_ONLY ? "Checked" : "Built"} ${resources.length} published resources across ${catalog.modules.length} module shelves.\n`);
}

main();
